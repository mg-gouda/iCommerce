// Generates src/theme.css from design-system/tokens.json: CSS variables (light + [data-theme=dark])
// plus a Tailwind v4 `@theme inline` block (the v4 equivalent of a preset) mapping utilities to those variables.
import { readFileSync, writeFileSync } from "node:fs"

const t = JSON.parse(readFileSync(new URL("../../../design-system/tokens.json", import.meta.url)))
const ref = (v) => v.replace(/^\{(.+)\}$/, "var(--$1)")
const themed = [...t.color.tokens, ...t.shadow.tokens]
const vars = (mode) =>
  themed.map(({ name, value }) => `  --${name}: ${ref(typeof value === "string" ? value : value[mode])};`).join("\n")
const plain = [...t.spacing.tokens, ...t.radius.tokens, ...t.zIndex.tokens].map(({ name, value }) => `  --${name}: ${value};`)
// next/font exposes hashed families as --font-plex-*; keep the token's names as fallbacks.
const font = (s) =>
  s
    .replace('"IBM Plex Sans Arabic"', 'var(--font-plex-arabic, "IBM Plex Sans Arabic")')
    .replace(/"IBM Plex Sans"(?! Arabic)/, 'var(--font-plex-sans, "IBM Plex Sans")')
    .replace('"IBM Plex Mono"', 'var(--font-plex-mono, "IBM Plex Mono")')

const css = `/* GENERATED by scripts/gen-theme.mjs from design-system/tokens.json. Do not edit. */
:root, [data-theme="light"] {
${vars("light")}
}
[data-theme="dark"] {
${vars("dark")}
  color-scheme: dark;
}
:root {
${plain.join("\n")}
}

@theme inline {
${t.color.tokens.map(({ name }) => `  --color-${name}: var(--${name});`).join("\n")}
${t.radius.tokens.map(({ name }) => `  --${name}: var(--${name});`).join("\n")}
${t.shadow.tokens.map(({ name }) => `  --${name}: var(--${name});`).join("\n")}
}

@theme static {
${Object.entries(t.type.families).map(([k, v]) => `  --font-${k}: ${font(v)};`).join("\n")}
}
`
writeFileSync(new URL("../src/theme.css", import.meta.url), css)
console.log("wrote src/theme.css")
